/**
 * Демонстрационный банк: собственные вопросы по ПДД РФ со структурой официальных билетов
 * (AB — 3 билета, CD — 2 билета; позиции 1–5, 6–10, 11–15, 16–20 = тематические блоки).
 * Полный официальный банк (по 40 билетов) подключается импортом: `npm run import:bank`.
 *
 * Варианты пишутся «правильный первым»; итоговая позиция правильного ответа выбирается детерминированно
 * по хешу id (числовые варианты сортируются по возрастанию) — чтобы правильный ответ не был всегда первым.
 */
interface Draft {
  readonly topics: readonly string[];
  readonly text: string;
  /** Первый вариант — правильный. */
  readonly options: readonly [string, ...string[]];
  readonly explanation: string;
  readonly refs?: readonly string[];
  readonly signs?: readonly string[];
}

function build(id: string, d: Draft): Question {
  const [correct, ...wrong] = d.options;
  let options: string[];
  if (d.options.every((o) => /^\d/.test(o))) {
    options = [...d.options].sort((a, b) => parseFloat(a.replace(',', '.')) - parseFloat(b.replace(',', '.')));
  } else {
    const pos = hashString(id) % d.options.length;
    options = [...wrong.slice(0, pos), correct, ...wrong.slice(pos)];
  }
  const image: QuestionImage | undefined = d.signs ? { kind: 'signs', signs: d.signs } : undefined;
  return {
    id,
    text: d.text,
    options,
    correctIndex: options.indexOf(correct),
    explanation: d.explanation,
    topicIds: d.topics,
    ...(image ? { image } : {}),
    ...(d.refs ? { ruleRefs: d.refs } : {}),
  };
}

